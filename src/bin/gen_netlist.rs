//! Generate a large synthetic hierarchical netlist for benchmarking.
//!
//!   gen_netlist --lines 10000000 --out bench_data
//!
//! writes `bench.v`, `bench.lib` and `queries.txt` into the output directory.
//! The design is a chain of unique blocks (each with a state register, a
//! counter, comparators, a bitmap lookup, a barrel shifter, a black-box memory
//! and random filler logic), one very large block, and a small module that is
//! instantiated by every block.

use std::fs::File;
use std::io::{BufWriter, Write};
use std::path::PathBuf;

use anyhow::{Context, Result};
use clap::Parser;

use netlist_search::synth::{ONE, Sig, Synth, ZERO};

#[derive(Parser)]
struct Args {
    /// Approximate number of lines to generate
    #[arg(long, default_value_t = 200_000)]
    lines: u64,
    /// Output directory
    #[arg(long, default_value = "bench_data")]
    out: PathBuf,
    /// Filler gates per ordinary block
    #[arg(long, default_value_t = 4000)]
    block_gates: usize,
    /// Share of all lines that go into the one very large block (percent)
    #[arg(long, default_value_t = 20)]
    big_percent: u64,
    #[arg(long, default_value_t = 1)]
    seed: u64,
}

const LEAF: &str = "module flag_sync (clk, d, q);
  input clk, d;
  output q;
  wire meta;
  DFFX1 meta_reg (.D(d), .CK(clk), .Q(meta));
  DFFX1 sync_reg (.D(meta), .CK(clk), .Q(q));
endmodule
";

/// One block; returns its Verilog text.
fn block(name: &str, seed: u64, filler: usize) -> String {
    let mut s = Synth::new(name, seed);
    let din = s.input_bus("din", 16);
    let en = s.input("en");
    let clk = Sig::Net("clk".into());
    let state = s.reg("state", 4);
    let cnt = s.reg("cnt", 8);
    let data = s.reg("data", 16);
    let bitmap = s.reg("bitmap", 16);

    let en_s = s.wire_bus("en_s", 1);
    s.instance(
        "flag_sync",
        "u_sync",
        &[("clk", &[clk.clone()]), ("d", &[en]), ("q", &en_s)],
    );
    let en = en_s[0].clone();

    let is5 = s.eq(&state, &Synth::constant(5, 4));
    let is5 = s.name_net(&is5, "st_is5");
    let is9 = s.eq(&state, &Synth::constant(9, 4));
    let lt = s.ult(&cnt, &Synth::constant(200, 8));
    let lt = s.name_net(&lt, "cnt_lt200");
    let hit = s.index(&bitmap, &din[..4]);
    let hit = s.name_net(&hit, "bm_hit");
    let cmp = s.ult(&data, &din);
    let cmp = s.name_net(&cmp, "data_lt_din");
    let a = s.and(&is5, &lt);
    let branch_a = s.name_net(&a, "branch_a");
    let b = s.and(&is9, &cmp);
    let branch_b = s.name_net(&b, "branch_b");

    // Counter: increments while enabled.
    let inc = s.add(&cnt, &Synth::constant(1, 8), &ZERO);
    let cnt_d: Vec<Sig> = (0..8).map(|i| s.mux(&en, &inc[i], &cnt[i])).collect();
    s.name_net(&cnt_d[7], "cnt_next7");
    s.set_d("cnt", &cnt_d);

    // Next state.
    let ns0 = s.mux(&branch_a, &hit, &state[0]);
    let ns1 = s.xor(&state[1], &branch_b);
    let t = s.or(&branch_a, &branch_b);
    let ns2 = s.mux(&t, &ONE, &state[2]);
    let ns3 = s.and(&state[3], &en);
    let ns: Vec<Sig> = [ns0, ns1, ns2, ns3]
        .iter()
        .enumerate()
        .map(|(i, x)| s.name_net(x, &format!("nstate[{i}]")))
        .collect();
    s.set_d("state", &ns);

    // Black-box memory and a shifter feed the filler logic.
    let mem_q = s.wire_bus("mem_q", 8);
    s.instance(
        "SRAM_256x8",
        "u_mem",
        &[("CLK", &[clk]), ("A", &cnt), ("D", &data[..8]), ("Q", &mem_q)],
    );
    let sh = s.shr(&data, &state[..3], &ZERO);
    s.name_net(&sh[2], "sh2");
    let mut ins: Vec<Sig> = data.clone();
    ins.extend(din.iter().cloned());
    ins.extend(mem_q);
    ins.extend(sh);
    let out = s.random_logic(&ins, filler, 32);
    let pick = |i: usize| out[i % out.len()].clone();
    let data_d: Vec<Sig> = (0..16).map(pick).collect();
    let bitmap_d: Vec<Sig> = (16..32).map(pick).collect();
    if let Sig::Net(_) = &data_d[3] {
        s.name_net(&data_d[3], "deep3");
    }
    s.set_d("data", &data_d);
    s.set_d("bitmap", &bitmap_d);
    s.output_bus("dout", &data);
    s.emit()
}

fn main() -> Result<()> {
    let args = Args::parse();
    std::fs::create_dir_all(&args.out)?;
    let path = args.out.join("bench.v");
    let mut w = BufWriter::with_capacity(
        1 << 22,
        File::create(&path).with_context(|| format!("cannot create {}", path.display()))?,
    );
    let mut lines = 0u64;
    let emit = |w: &mut BufWriter<File>, text: &str| -> Result<u64> {
        w.write_all(text.as_bytes())?;
        Ok(text.bytes().filter(|&c| c == b'\n').count() as u64)
    };
    emit(&mut w, "// synthetic benchmark netlist generated by gen_netlist\n")?;
    lines += emit(&mut w, LEAF)?;

    let mut blocks: Vec<String> = Vec::new();
    let big_lines = args.lines * args.big_percent / 100;
    if big_lines > 20_000 {
        // About 2.3 lines per filler gate (inverters, wire declarations).
        let text = block("blk_big", args.seed ^ 0xb16, (big_lines as f64 / 2.3) as usize);
        lines += emit(&mut w, &text)?;
        blocks.push("blk_big".into());
    }
    let mut i = 0u64;
    loop {
        let name = format!("blk_{i}");
        let text = block(&name, args.seed.wrapping_mul(7919).wrapping_add(i * 104_729 + 1), args.block_gates);
        lines += emit(&mut w, &text)?;
        blocks.push(name);
        i += 1;
        if lines + blocks.len() as u64 + 16 >= args.lines {
            break;
        }
    }

    // Top: the blocks in a ring; half of them inside flattened-style names.
    let mut top = String::from("module bench_top (clk, en, pin, pout);\n  input clk, en;\n  input [15:0] pin;\n  output [15:0] pout;\n");
    for k in 0..blocks.len() {
        top.push_str(&format!("  wire [15:0] link_{k};\n"));
    }
    for (k, b) in blocks.iter().enumerate() {
        let din = if k == 0 { "pin".to_string() } else { format!("link_{}", k - 1) };
        let inst = if k % 2 == 1 { format!("\\u_core/u_{b} ") } else { format!("u_{b}") };
        top.push_str(&format!("  {b} {inst} (.clk(clk), .en(en), .din({din}), .dout(link_{k}));\n"));
    }
    top.push_str(&format!("  assign pout = link_{};\nendmodule\n", blocks.len() - 1));
    lines += emit(&mut w, &top)?;
    w.flush()?;
    drop(w);

    std::fs::write(
        args.out.join("bench.lib"),
        include_str!("../../tests/fixtures/basic.lib"),
    )?;
    let last = blocks.len() - 1;
    let mid = blocks.len() / 2 & !1;
    let odd = if last % 2 == 1 { last } else { last.saturating_sub(1) };
    let mut q = String::new();
    for (inst, wire) in [
        (format!("u_{}", blocks[mid]), "nstate[2]"),
        (format!("u_{}", blocks[mid]), "nstate[0]"),
        (format!("u_{}", blocks[mid]), "cnt_next7"),
        (format!("u_{}", blocks[mid]), "sh2"),
        (format!("u_{}", blocks[mid]), "deep3"),
        (format!("u_core/u_{}", blocks[odd]), "branch_b"),
        (format!("u_{}", blocks[0]), "nstate[0]"),
        (String::new(), "pout[3]"),
    ] {
        q.push_str(&format!("--inst \"{inst}\" --wire \"{wire}\"\n"));
    }
    std::fs::write(args.out.join("queries.txt"), q)?;

    let size = std::fs::metadata(&path)?.len();
    println!(
        "wrote {}: {} lines, {:.1} MB, {} blocks",
        path.display(),
        lines,
        size as f64 / 1e6,
        blocks.len()
    );
    Ok(())
}
